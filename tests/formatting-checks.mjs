import assert from 'node:assert/strict';

export async function checkFormatting(page, baseUrl) {
  await page.goto(`${baseUrl}/examples/formatting.html`);
  await page.waitForFunction(() => window.formattingHandle);
  const input = page.getByLabel('Formatted content');
  const field = page.locator('#formatting [data-editor-document]');
  const preview = page.getByRole('region', { name: 'Formatted preview' });
  const select = async (start, end) => {
    await input.focus();
    await input.evaluate((node, [start, end]) => node.setSelectionRange(start, end), [start, end]);
  };
  await input.fill('Hello world');
  await select(0, 5);
  await page.getByRole('button', { name: 'Bold', exact: true }).click();
  assert.equal(await preview.locator('strong').textContent(), 'Hello');
  assert.deepEqual(await input.evaluate(node => [node.selectionStart, node.selectionEnd]), [0, 5]);
  await input.press('Control+i');
  assert.equal(await preview.locator('strong em').textContent(), 'Hello');
  await input.press('Control+z');
  assert.equal(await preview.locator('em').count(), 0);
  await input.press('Control+Shift+z');
  assert.equal(await preview.locator('strong em').textContent(), 'Hello');
  await page.getByRole('button', { name: 'Bold', exact: true }).click();
  assert.equal(await preview.locator('strong').count(), 0);
  assert.equal(await preview.locator('em').textContent(), 'Hello');
  await input.fill('aa');
  await select(0, 1);
  await input.press('Control+b');
  await input.press('Backspace');
  assert.equal(await input.inputValue(), 'a');
  assert.equal(await preview.locator('strong').count(), 0, 'Deleting the marked first repeated character must not delete the unmarked second one');
  await input.press('Control+z');
  assert.equal(await preview.locator('strong').textContent(), 'a');
  await select(1, 1);
  await input.press('Delete');
  assert.equal(await preview.locator('strong').textContent(), 'a');
  await input.fill('A🙂 B\nC');
  await select(1, 3);
  await input.press('Control+b');
  assert.equal(await preview.locator('strong').textContent(), '🙂');
  await select(1, 7);
  await page.getByRole('button', { name: 'Italic', exact: true }).click();
  let document = JSON.parse(await field.inputValue());
  assert.equal(document.blocks.length, 2);
  assert.ok(document.blocks[0].children.some(run => run.text === '🙂' && run.marks.join() === 'bold,italic'));
  assert.equal(document.blocks[1].children[0].marks.join(), 'italic');
  await input.fill('<script>evil()</script>');
  assert.equal(await preview.locator('script').count(), 0);
  assert.equal(await preview.textContent(), '<script>evil()</script>');
  await select(0, (await input.inputValue()).length);
  await page.getByRole('button', { name: 'Bold', exact: true }).click();
  const saved = await field.inputValue();
  await page.evaluate(async () => {
    const root = window.document.querySelector('[data-legura-editor="formatting"]');
    const saved = root.querySelector('[data-editor-document]').value;
    window.formattingHandle.destroy();
    root.dataset.document = saved;
    const { mountFormattingEditor } = await import('/src/js/formatting-editor.js');
    window.formattingHandle = mountFormattingEditor(root);
  });
  assert.equal(await field.inputValue(), saved);
  await input.fill('x'.repeat(20001));
  assert.equal(await field.isDisabled(), true);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  assert.equal(await field.inputValue(), saved);
  await input.fill('Completely changed');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  assert.equal(await field.inputValue(), saved);
  await input.evaluate(node => node.dispatchEvent(new CompositionEvent('compositionstart')));
  assert.equal(await field.isDisabled(), true);
  await input.evaluate(node => {
    node.value += ' Č';
    node.dispatchEvent(new InputEvent('input', { bubbles: true, isComposing: true }));
    node.dispatchEvent(new CompositionEvent('compositionend'));
  });
  assert.equal(await field.isDisabled(), false);
  assert.ok((await input.inputValue()).endsWith(' Č'));
  await page.evaluate(async () => {
    const form = window.document.querySelector('#formatting').cloneNode(true);
    form.id = 'formatting-second';
    window.document.querySelector('main').append(form);
    const { mountFormattingEditor } = await import('/src/js/formatting-editor.js');
    window.secondFormattingHandle = mountFormattingEditor(form.querySelector('[data-legura-editor]'));
  });
  const original = await field.inputValue();
  await page.locator('#formatting-second textarea').fill('Independent formatting');
  assert.equal(await field.inputValue(), original);
  await page.setViewportSize({ width: 320, height: 800 });
  assert.ok(await page.evaluate(() => window.document.documentElement.scrollWidth <= innerWidth));
  await page.evaluate(() => window.formattingHandle.destroy());
  assert.equal(await field.isDisabled(), true);
  assert.equal(await page.locator('#formatting [data-editor-command]:enabled').count(), 0);
  console.log('Formatting pilot passed: selection, bold/italic toggles, keyboard undo/redo, Unicode/multiple paragraphs, safe preview, round-trip, invalid recovery, reset, composition, isolation and mobile.');
}
